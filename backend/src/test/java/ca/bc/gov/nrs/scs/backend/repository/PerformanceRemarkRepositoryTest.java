  @Test
  void delete_bindsIdToDeleteRecProcedure() throws Exception {
    JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
    PerformanceRemarkRepository repository = new PerformanceRemarkRepository(jdbcTemplate);

    AtomicReference<CallableStatement> captured = new AtomicReference<>();
    AtomicReference<String> capturedSql = new AtomicReference<>();
    stubJdbcExecute(jdbcTemplate, null, captured, capturedSql);

    repository.delete(1001L);

    // Call string targets delete_rec — a procedure (no return placeholder) with one IN param.
    assertTrue(capturedSql.get().contains("scs_scaler_performanc_rmrk_pkg.delete_rec"));
    assertEquals(1, capturedSql.get().chars().filter(c -> c == '?').count());

    // The PK is bound from index 1 (no cursor/return slot to skip).
    verify(captured.get()).setLong(1, 1001L);
    verify(captured.get()).execute();
  }

  private void stubJdbcExecute(
      JdbcTemplate jdbcTemplate,
      ResultSet rs,
      AtomicReference<CallableStatement> captured,
      AtomicReference<String> capturedSql) {
    when(jdbcTemplate.execute(any(CallableStatementCreator.class), any(CallableStatementCallback.class)))
        .thenAnswer(invocation -> {
          CallableStatementCreator creator = invocation.getArgument(0);
          CallableStatementCallback<?> callback = invocation.getArgument(1);

          Connection con = mock(Connection.class);
          CallableStatement cs = mock(CallableStatement.class);
          when(con.prepareCall(anyString())).thenAnswer(call -> {
            capturedSql.set(call.getArgument(0));
            return cs;
          });
          captured.set(cs);

          creator.createCallableStatement(con);
          if (rs != null) {
            when(cs.getObject(1)).thenReturn(rs);
          }

          return callback.doInCallableStatement(cs);
        });
  }

