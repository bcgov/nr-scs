    when(rs.getString("scaler_performance_outcm_code")).thenReturn("R");
    when(rs.getString("outcome_desc")).thenReturn("Resolved after review");
    when(rs.getDate("suspend_start_date")).thenReturn(Date.valueOf(LocalDate.of(2025, 2, 1)));
    when(rs.getObject("check_scale_id")).thenReturn(55001L);
    when(rs.getLong("check_scale_id")).thenReturn(55001L);
    when(rs.getDate("suspend_end_date")).thenReturn(Date.valueOf(LocalDate.of(2025, 3, 1)));
    when(rs.getTimestamp("entry_timestamp")).thenReturn(null);
    when(rs.getString("entry_userid")).thenReturn("JSMITH");
    when(rs.getTimestamp("update_timestamp")).thenReturn(null);
    when(rs.getString("update_userid")).thenReturn("JSMITH");
    when(rs.getObject("revision_count")).thenReturn(1L);
    when(rs.getLong("revision_count")).thenReturn(1L);

