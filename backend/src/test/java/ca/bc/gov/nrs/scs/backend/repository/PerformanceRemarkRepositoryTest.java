  @Test
  void findByScalerLicenceNo_bindsLicenceAndMapsRows() throws Exception {
    JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
    PerformanceRemarkRepository repository = new PerformanceRemarkRepository(jdbcTemplate);

    ResultSet rs = remarkResultSet();
    AtomicReference<CallableStatement> captured = new AtomicReference<>();
    AtomicReference<String> capturedSql = new AtomicReference<>();
    stubJdbcExecute(jdbcTemplate, rs, captured, capturedSql);

    List<PerformanceRemarkRecord> out = repository.findByScalerLicenceNo("1234");

    // Call string targets the verified package + search_recs with 13 IN placeholders.
    assertTrue(capturedSql.get().contains("scs_scaler_performanc_rmrk_pkg.search_recs"));
    assertEquals(13, capturedSql.get().chars().filter(c -> c == '?').count() - 1);

    // p_scaler_performance_rmrk_d (index 2) is null; the licence (index 3) is bound.
    verify(captured.get()).setNull(2, Types.NUMERIC);
    verify(captured.get()).setString(3, "1234");

    assertEquals(1, out.size());
    PerformanceRemarkRecord record = out.get(0);
    assertEquals(1001L, record.scalerPerformanceRemarkId());
    assertEquals("1234", record.scalerLicenceNo());
    assertEquals(LocalDate.of(2025, 1, 10), record.loggedTimestamp());
    assertEquals("Late submission", record.performanceRemarkDesc());
    assertEquals("W", record.scalerPerformanceActnCode());
    assertEquals("R", record.scalerPerformanceOutcmCode());
    assertEquals(LocalDate.of(2025, 2, 1), record.suspendStartDate());
    assertEquals(LocalDate.of(2025, 3, 1), record.suspendEndDate());
    assertEquals(55001L, record.checkScaleId());
  }

