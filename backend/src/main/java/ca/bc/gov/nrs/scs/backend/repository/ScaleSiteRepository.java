package ca.bc.gov.nrs.scs.backend.repository;

import static ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils.currentUserIdOrSystem;
import static ca.bc.gov.nrs.scs.backend.util.SCSUtils.padClientNumber;

import java.sql.SQLException;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteCoordinate;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSite;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteCore;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteOwnerInfo;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteSearchCriteria;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteSearchEntry;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteSummaryCore;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.ScaleSiteTombstoneRecord;
import ca.bc.gov.nrs.scs.backend.domain.scalesite.SiteScalingMethod;

@Repository
public class ScaleSiteRepository extends AbstractRepository {

  private static final String SCALE_SITE_SEARCH_PKG = "scs_scale_site_search_vw_pkg";
  private static final String SCALE_SITE_PKG = "scs_scale_site_pkg";
  private static final String SCALE_SITE_OWNER_SEARCH_PKG = "scs_scale_site_owner_vw_pkg";
  private static final String SCALE_SITE_TOMBSTONE_SEARCH_PKG = "SCS_SCALE_SITE_TOMBSTON_VW_PKG";
  private static final String SCALE_SITE_SCALING_METHOD_PKG = "scs_site_scaling_method_pkg";

  public ScaleSiteRepository(JdbcTemplate jdbcTemplate) {
    super(jdbcTemplate);
  }

  public String createScaleSite(ScaleSite scaleSite) {
    final String userId = currentUserIdOrSystem();

    return queryCursorCall(buildInsertRecCall(SCALE_SITE_PKG, 15),
        cs -> bindScaleSiteColumns(
                ParameterBinder.afterReturn(cs)
                    .nullString(),  // scale_site_id_nmbr — generated by package
                scaleSite)
            .string(userId)         // entry_userid
            .string(userId),        // update_userid
        rs -> (rs != null && rs.next()) ? rs.getString("scale_site_id_nmbr") : null);
  }

  public void createSiteScalingMethod(String scaleSiteIdNmbr, SiteScalingMethod method) {
    if (method == null || method.scaleMethodTypeCode() == null || method.scaleMethodTypeCode().isBlank()) {
      return;
    }

    final String userId = currentUserIdOrSystem();
    queryCursorCall(buildInsertRecCall(SCALE_SITE_SCALING_METHOD_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleSiteIdNmbr)
            .string(method.scaleMethodTypeCode())
            .string(method.scaleSitePriorityCode())
            .string(userId)
            .string(userId),
        rs -> null);
  }

  public void updateScaleSite(ScaleSite scaleSite) {
    final String userId = currentUserIdOrSystem();

    queryCursorCall(buildUpdateRecCall(SCALE_SITE_PKG, 15),
        cs -> bindScaleSiteColumns(
                ParameterBinder.afterReturn(cs)
                    .string(scaleSite.scaleSiteIdNmbr()),
                scaleSite)
            .nullString()           // entry_userid — not written on update
            .string(userId),        // update_userid
        rs -> null);
  }

  /**
   * Binds the twelve scale-site columns {@code insert_rec} and {@code update_rec} share, in package
   * order, after the caller has bound the leading {@code scale_site_id_nmbr}; the caller then binds
   * the trailing audit userids.
   */
  private ParameterBinder bindScaleSiteColumns(ParameterBinder binder, ScaleSite scaleSite)
      throws SQLException {
    final ScaleSiteCoordinate latitude = scaleSite.latitude();
    final ScaleSiteCoordinate longitude = scaleSite.longitude();
    return binder
            .longValue(scaleSite.orgUnitNo())
            .string(scaleSite.ownerClientNumber())
            .string(scaleSite.ownerClientLocnCode())
            .string(scaleSite.siteName())
            .string(scaleSite.siteLocation())
            .string(scaleSite.timberBrand())
            .intValue(latitude == null ? null : latitude.degrees())
            .intValue(latitude == null ? null : latitude.minutes())
            .intValue(latitude == null ? null : latitude.seconds())
            .intValue(longitude == null ? null : longitude.degrees())
            .intValue(longitude == null ? null : longitude.minutes())
            .intValue(longitude == null ? null : longitude.seconds());
  }

  public void deleteSiteScalingMethodsForSite(
      String scaleSiteIdNmbr, List<SiteScalingMethod> existingMethods) {
    if (existingMethods == null || existingMethods.isEmpty()) {
      return;
    }
    for (SiteScalingMethod method : existingMethods) {
      if (method == null || method.scaleMethodTypeCode() == null || method.scaleMethodTypeCode().isBlank()) {
        continue;
      }
      deleteSiteScalingMethod(scaleSiteIdNmbr, method.scaleMethodTypeCode());
    }
  }

  private void deleteSiteScalingMethod(String scaleSiteIdNmbr, String scaleMethodTypeCode) {
    if (scaleMethodTypeCode == null || scaleMethodTypeCode.isBlank()) {
      return;
    }
    executeVoidCall(buildDeleteRecCall(SCALE_SITE_SCALING_METHOD_PKG, 2),
        cs -> ParameterBinder.fromStart(cs)
            .string(scaleSiteIdNmbr)
            .string(scaleMethodTypeCode));
  }

  public List<ScaleSiteSearchEntry> searchScaleSites(ScaleSiteSearchCriteria criteria) {
    final List<String> methodTypes = criteria.methodTypes() == null ? List.of() : criteria.methodTypes();
    final boolean weightScale = methodTypes.contains("W");
    final boolean pieceScale = methodTypes.contains("P");
    final boolean specialForestProduct = methodTypes.contains("S");
    final boolean cruiseBased = methodTypes.contains("C");

    return queryCursorCall(buildSearchRecsCall(SCALE_SITE_SEARCH_PKG, 14),
        cs -> ParameterBinder.afterReturn(cs)
            .string(criteria.scaleSiteIdNmbr())
            .longValue(criteria.orgUnitNo())
            .nullString()
            .string(toLegacyFlag(weightScale))
            .string(toLegacyFlag(pieceScale))
            .string(toLegacyFlag(specialForestProduct))
            .string(toLegacyFlag(cruiseBased))
            .string(criteria.ownerClientNumber())
            .string(criteria.siteName())
            .string(criteria.ownerClientLocnCode())
            .nullString()
            .nullString()
            .intValue(criteria.primarySort())
            .intValue(criteria.secondarySort()),
        rs -> {
          List<ScaleSiteSearchEntry> out = new ArrayList<>();
          while (rs.next()) {
            out.add(new ScaleSiteSearchEntry(
                rs.getString(1),
                rs.getString(9),
                rs.getString(12),
                rs.getString(11),
                rs.getString(3),
                padClientNumber(rs.getString(8)),
                rs.getString(10)));
          }
          return out;
        });
  }

  public ScaleSiteCore getScaleSite(String scaleSiteIdNmbr) {
    ScaleSiteSummaryCore summaryCore = getScaleSiteSummaryCore(scaleSiteIdNmbr);
    if (summaryCore == null) {
      return null;
    }

    return new ScaleSiteCore(
        summaryCore.scaleSiteIdNmbr(),
        summaryCore.siteName(),
        summaryCore.siteLocation());
  }

  public ScaleSiteSummaryCore getScaleSiteSummaryCore(String scaleSiteIdNmbr) {
    return queryCursorCall(buildSelectRecCall(SCALE_SITE_PKG, 1),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleSiteIdNmbr),
        rs -> {
          if (rs == null || !rs.next()) {
            return null;
          }
          return new ScaleSiteSummaryCore(
              rs.getString(1),
              getLongNullable(rs, 2),
              rs.getString(3),
              rs.getString(4),
              rs.getString(5),
              rs.getString(6),
              rs.getString(7),
              getIntNullable(rs, 8),
              getIntNullable(rs, 9),
              getIntNullable(rs, 10),
              getIntNullable(rs, 11),
              getIntNullable(rs, 12),
              getIntNullable(rs, 13),
              getOffsetDateTimeNullable(rs, 14),
              rs.getString(15),
              getOffsetDateTimeNullable(rs, 16),
              rs.getString(17),
              getLongNullable(rs, 18));
        });
  }

  public ScaleSiteTombstoneRecord getScaleSiteTombstone(String scaleSiteIdNmbr) {
    return queryCursorCall(buildSearchRecsCall(SCALE_SITE_TOMBSTONE_SEARCH_PKG, 6),
        cs -> ParameterBinder.afterReturn(cs)
            .nullString()
            .nullString()
            .string(scaleSiteIdNmbr)
            .nullString()
            .intValue(1)
            .intValue(1),
        rs -> {
          if (rs == null || !rs.next()) {
            return null;
          }
          return new ScaleSiteTombstoneRecord(
              rs.getString(3),
              rs.getString(4),
              rs.getString(2),
              rs.getString(1));
        });
  }

  public ScaleSiteOwnerInfo getScaleSiteOwner(String scaleSiteIdNmbr) {
    return queryCursorCall(buildSearchRecsCall(SCALE_SITE_OWNER_SEARCH_PKG, 20),
        cs -> {
          cs.setString(2, scaleSiteIdNmbr);
          for (int index = 3; index <= 19; index++) {
            cs.setNull(index, Types.VARCHAR);
          }
          cs.setInt(20, 2);
          cs.setInt(21, 3);
        },
        rs -> {
          if (rs == null || !rs.next()) {
            return null;
          }
          return new ScaleSiteOwnerInfo(
              rs.getString(4),
              rs.getString(5),
              rs.getString(6));
        });
  }

  public List<SiteScalingMethod> getScaleSiteSummarySiteTypes(String scaleSiteIdNmbr) {
    return queryCursorCall(buildSearchRecsCall(SCALE_SITE_SCALING_METHOD_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleSiteIdNmbr)
            .nullString()
            .nullString()
            .nullString()
            .nullString(),
        rs -> {
          List<SiteScalingMethod> out = new ArrayList<>();
          while (rs != null && rs.next()) {
            out.add(new SiteScalingMethod(
                rs.getString(2),
                rs.getString(3)));
          }
          return out;
        });
  }


  private String toLegacyFlag(boolean selected) {
    return selected ? "Y" : null;
  }

}
