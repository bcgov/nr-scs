  public List<ScaleAuthCondition> getMarkSiteDesignationConditions(Long authorizationId) {
    Set<ConditionKey> keys = queryLinkedConditionKeys(authorizationId);

    List<ScaleAuthCondition> mandatory = getMandatoryMarkSiteConditions();
    List<ScaleAuthCondition> linked = getLinkedMarkSiteConditions(keys);

    if (linked.isEmpty()) {
      return sortConditions(mandatory);
    }

    List<ScaleAuthCondition> combined = new ArrayList<>(mandatory);
    for (ScaleAuthCondition condition : linked) {
      if (!containsCondition(combined, condition)) {
        combined.add(condition);
      }
    }

    return sortConditions(combined);
  }

