  private List<ScaleAuthCondition> getLinkedMarkSiteConditions(Set<ConditionKey> keys) {
    if (keys == null || keys.isEmpty()) {
      return List.of();
    }

    List<ScaleAuthCondition> out = new ArrayList<>();
    for (ConditionKey key : keys) {
      ScaleAuthCondition condition = getScaleAuthCondition(key.classCode(), key.conditionId());
      if (condition != null) {
        out.add(condition);
      }
    }
    return out;
  }

  private List<ScaleAuthCondition> sortConditions(List<ScaleAuthCondition> rows) {
    if (rows == null || rows.isEmpty()) {
      return List.of();
    }
    rows.sort(Comparator.comparing(c -> {
      Integer sortOrder = c.getSortOrderNo();
      return sortOrder == null ? Integer.MAX_VALUE : sortOrder;
    }));
    return rows;
  }

  private List<ScaleAuthCondition> getMandatoryMarkSiteConditions() {
    return queryCursorCall(buildFunctionCall(SCALE_AUTH_CONDITION_PKG, "search_active_recs", 10),
        cs -> ParameterBinder.afterReturn(cs)
            .string("MSD")
            .nullNumeric()
            .nullString()
            .nullString()
            .string("Y")
            .nullNumeric()
            .nullDate()
            .nullDate()
            .nullString()
            .nullString(),
        rs -> {
          List<ScaleAuthCondition> rows = new ArrayList<>();
          while (rs.next()) {
            rows.add(mapScaleAuthCondition(rs));
          }
          return rows;
        });
  }

  private boolean containsCondition(List<ScaleAuthCondition> rows, ScaleAuthCondition candidate) {
    if (candidate == null) {
      return false;
    }

    for (ScaleAuthCondition row : rows) {
      if (row == null) {
        continue;
      }
      if (safeEquals(row.getScaleConditionClassCode(), candidate.getScaleConditionClassCode())
          && safeEquals(row.getScaleAuthConditionId(), candidate.getScaleAuthConditionId())) {
        return true;
      }
    }

    return false;
  }

  private boolean safeEquals(Object left, Object right) {
    return left == right || (left != null && left.equals(right));
  }

  private ScaleAuthCondition mapScaleAuthCondition(ResultSet rs) throws SQLException {
    ScaleAuthCondition condition = new ScaleAuthCondition();
    condition.setScaleConditionClassCode(rs.getString("scale_condition_class_code"));
    condition.setScaleAuthConditionId(getLongNullable(rs, "scale_auth_condition_id"));
    condition.setScaleAuthConditionTitle(rs.getString("scale_auth_condition_title"));
    condition.setScaleAuthConditionDesc(rs.getString("scale_auth_condition_desc"));
    condition.setMinistryStandardInd(rs.getString("ministry_standard_ind"));
    condition.setSortOrderNo(getIntNullable(rs, "sort_order_no"));
    condition.setEffectiveDate(getLocalDateNullable(rs, "effective_date"));
    condition.setExpiryDate(getLocalDateNullable(rs, "expiry_date"));
    return condition;
  }

