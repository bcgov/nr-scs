  /**
   * Deletes all mutable associations (scale sites, species content, non-mandatory conditions)
   * for the given authorization so they can be replaced with updated values.
   */
  public void deleteMarkSiteDesignationAssociations(Long authorizationId) {
    if (authorizationId == null) {
      return;
    }
    deleteMarkSiteScaleSiteAssociations(authorizationId);
    deleteMarkSiteSpeciesContentAssociations(authorizationId);
    deleteMarkSiteConditionAssociations(authorizationId);
    deleteMarkSiteExceptionAssociations(authorizationId);
  }

  private void deleteMarkSiteExceptionAssociations(Long authorizationId) {
    List<String> exceptions = getMarkSiteDesignationExceptions(authorizationId);
    if (exceptions == null || exceptions.isEmpty()) {
      return;
    }
    for (String exemptMarkMethodCode : exceptions) {
      if (exemptMarkMethodCode == null || exemptMarkMethodCode.isBlank()) {
        continue;
      }
      executeVoidCall(buildDeleteRecCall(DESIGNATED_EXEMPT_MARK_METHOD_PKG, 2),
          cs -> ParameterBinder.fromStart(cs)
              .longValue(authorizationId)
              .string(exemptMarkMethodCode));
    }
  }

  private void deleteMarkSiteScaleSiteAssociations(Long authorizationId) {
    List<MarkSiteDesignationScaleSite> sites = getMarkSiteDesignationScaleSites(authorizationId);
    if (sites == null || sites.isEmpty()) {
      return;
    }
    for (MarkSiteDesignationScaleSite site : sites) {
      String siteId = site == null ? null : site.getScaleSiteIdNmbr().orElse(null);
      if (siteId == null || siteId.isBlank()) {
        continue;
      }
      executeVoidCall(buildDeleteRecCall(HAULING_MARK_SITE_PKG, 2),
          cs -> ParameterBinder.fromStart(cs)
              .longValue(authorizationId)
              .string(siteId));
    }
  }

  private void deleteMarkSiteSpeciesContentAssociations(Long authorizationId) {
    List<MarkSiteDesignationSpeciesContent> species = getMarkSiteDesignationSpeciesContent(authorizationId);
    if (species == null || species.isEmpty()) {
      return;
    }
    for (MarkSiteDesignationSpeciesContent row : species) {
      String code = row == null ? null : row.getScaleSpeciesCode().orElse(null);
      if (code == null || code.isBlank()) {
        continue;
      }
      executeVoidCall(buildDeleteRecCall(SPECIES_CONTENT_PKG, 2),
          cs -> ParameterBinder.fromStart(cs)
              .longValue(authorizationId)
              .string(code));
    }
  }

  private Set<ConditionKey> queryLinkedConditionKeys(Long authorizationId) {
    return queryCursorCall(buildSearchRecsCall(HAULING_MARK_SITE_CONDITION_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(authorizationId)
            .nullString()
            .nullNumeric()
            .nullString()
            .nullString(),
        rs -> {
          Set<ConditionKey> out = new LinkedHashSet<>();
          while (rs.next()) {
            String classCode = rs.getString(2);
            Long conditionId = getLongNullable(rs, 3);
            if (classCode == null || classCode.isBlank() || conditionId == null) {
              continue;
            }
            out.add(new ConditionKey(classCode, conditionId));
          }
          return out;
        });
  }

  private void deleteMarkSiteConditionAssociations(Long authorizationId) {
    Set<ConditionKey> keys = queryLinkedConditionKeys(authorizationId);
    for (ConditionKey key : keys) {
      executeVoidCall(buildDeleteRecCall(HAULING_MARK_SITE_CONDITION_PKG, 3),
          cs -> ParameterBinder.fromStart(cs)
              .longValue(authorizationId)
              .string(key.classCode())
              .longValue(key.conditionId()));
    }
  }
