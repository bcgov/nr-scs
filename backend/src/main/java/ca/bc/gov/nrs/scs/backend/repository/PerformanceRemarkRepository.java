package ca.bc.gov.nrs.scs.backend.repository;

import static ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils.currentUserIdOrSystem;

import ca.bc.gov.nrs.scs.backend.domain.performanceremark.PerformanceRemarkCommand;
import ca.bc.gov.nrs.scs.backend.domain.performanceremark.PerformanceRemarkCreateCommand;
import ca.bc.gov.nrs.scs.backend.domain.performanceremark.PerformanceRemarkRecord;
import ca.bc.gov.nrs.scs.backend.domain.performanceremark.PerformanceRemarkUpdateCommand;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

/**
 * Data access for scaler performance-remark records via {@code scs_scaler_performanc_rmrk_pkg}.
 *
 * <p>Verified signature ({@code scs_scaler_performanc_rmrk_pkg.pks}). {@code search_recs} takes 13
 * IN params, in order:
 * <ol>
 *   <li>{@code p_scaler_performance_rmrk_d} (NUMBER)</li>
 *   <li>{@code p_scaler_licence_no} (VARCHAR2)</li>
 *   <li>{@code p_logged_timestamp} (DATE)</li>
 *   <li>{@code p_logged_userid} (VARCHAR2)</li>
 *   <li>{@code p_performance_remark_desc} (VARCHAR2)</li>
 *   <li>{@code p_scaler_performance_ctn_cd} (VARCHAR2 — action code)</li>
 *   <li>{@code p_scaler_performance_tcm_cd} (VARCHAR2 — outcome code)</li>
 *   <li>{@code p_outcome_desc} (VARCHAR2)</li>
 *   <li>{@code p_suspend_start_date} (DATE)</li>
 *   <li>{@code p_check_scale_id} (NUMBER)</li>
 *   <li>{@code p_suspend_end_date} (DATE)</li>
 *   <li>{@code p_entry_userid} (VARCHAR2)</li>
 *   <li>{@code p_update_userid} (VARCHAR2)</li>
 * </ol>
 * The package orders results by {@code logged_timestamp desc, scaler_performance_remark_id}.
 * Cursor columns (in order): {@code scaler_performance_remark_id, scaler_licence_no,
 * logged_timestamp, logged_userid, performance_remark_desc, scaler_performance_actn_code,
 * scaler_performance_outcm_code, outcome_desc, suspend_start_date, check_scale_id,
 * suspend_end_date, entry_timestamp, entry_userid, update_timestamp, update_userid,
 * revision_count}.
 */
@Repository
public class PerformanceRemarkRepository extends AbstractRepository {

  private static final String PERFORMANCE_REMARK_PKG = "scs_scaler_performanc_rmrk_pkg";

  public PerformanceRemarkRepository(JdbcTemplate jdbcTemplate) {
    super(jdbcTemplate);
  }

  /** Lists every performance remark for a scaler (filters {@code search_recs} by licence only). */
  public List<PerformanceRemarkRecord> findByScalerLicenceNo(String scalerLicenceNo) {
    return queryCursorCall(buildSearchRecsCall(PERFORMANCE_REMARK_PKG, 13),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()            // p_scaler_performance_rmrk_d
            .string(scalerLicenceNo)  // p_scaler_licence_no
            .nullDate()               // p_logged_timestamp
            .nullString()             // p_logged_userid
            .nullString()             // p_performance_remark_desc
            .nullString()             // p_scaler_performance_ctn_cd
            .nullString()             // p_scaler_performance_tcm_cd
            .nullString()             // p_outcome_desc
            .nullDate()               // p_suspend_start_date
            .nullNumeric()            // p_check_scale_id
            .nullDate()               // p_suspend_end_date
            .nullString()             // p_entry_userid
            .nullString(),            // p_update_userid
        rs -> {
          List<PerformanceRemarkRecord> remarks = new ArrayList<>();
          while (rs.next()) {
            remarks.add(mapRow(rs));
          }
          return remarks;
        });
  }

  /**
   * Inserts a performance-remark row via {@code insert_rec} and returns the created row. The
   * primary key is generated by the database (bound null); the logged / entry / update userids are
   * all set to the current user, mirroring {@code ScalerPerformanceRemarkCreateAction}. {@code insert_rec}
   * takes the same 13 IN params as {@code search_recs} in the same order (see class javadoc), except
   * {@code p_logged_userid} carries the acting user rather than a search filter.
   */
  public PerformanceRemarkRecord insert(
      String scalerLicenceNo,
      PerformanceRemarkCreateCommand command
  ) {
    final String userId = currentUserIdOrSystem();

    return queryCursorCall(buildInsertRecCall(PERFORMANCE_REMARK_PKG, 13),
        cs -> bindRemarkColumns(
            ParameterBinder.afterReturn(cs)
                .nullNumeric(),  // in_scaler_performance_rmrk_d — generated by DB
            scalerLicenceNo, command, userId),
        this::requireRemarkRow);
  }

  /**
   * Loads a single performance-remark row by id via {@code select_rec} (one IN param: the PK), or
   * returns {@code null} when no row exists. Used to confirm a remark exists and belongs to the
   * scaler before an update.
   */
  public PerformanceRemarkRecord findById(Long scalerPerformanceRemarkId) {
    return queryCursorCall(buildSelectRecCall(PERFORMANCE_REMARK_PKG, 1),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scalerPerformanceRemarkId),  // p_scaler_performance_rmrk_d
        rs -> rs.next() ? mapRow(rs) : null);
  }

  /**
   * Updates a performance-remark row via {@code update_rec} and returns the refreshed row. The
   * logged / update userids are set to the current user, mirroring
   * {@code ScalerPerformanceRemarkUpdateAction}. {@code update_rec} takes the same 13 IN params as
   * {@code insert_rec} in the same order (see class javadoc); on update the PK ({@code
   * p_scaler_performance_rmrk_d}) carries the id of the row being updated and {@code p_entry_userid}
   * is accepted but not written by the package.
   */
  public PerformanceRemarkRecord update(
      String scalerLicenceNo,
      Long scalerPerformanceRemarkId,
      PerformanceRemarkUpdateCommand command
  ) {
    final String userId = currentUserIdOrSystem();

    return queryCursorCall(buildUpdateRecCall(PERFORMANCE_REMARK_PKG, 13),
        cs -> bindRemarkColumns(
            ParameterBinder.afterReturn(cs)
                .longValue(scalerPerformanceRemarkId),  // in_scaler_performance_rmrk_d — PK of row
            scalerLicenceNo, command, userId),
        this::requireRemarkRow);
  }

  /**
   * Binds IN params 2–13 of {@code insert_rec} / {@code update_rec} (identical for both, see the
   * class javadoc) after the caller has bound the primary key: the logged / entry / update userids
   * all carry the acting user ({@code p_entry_userid} is accepted but not written on update).
   */
  private ParameterBinder bindRemarkColumns(
      ParameterBinder binder,
      String scalerLicenceNo,
      PerformanceRemarkCommand command,
      String userId) throws SQLException {
    return binder
            .string(scalerLicenceNo)                          // in_scaler_licence_no
            .date(command.loggedTimestamp())                  // in_logged_timestamp
            .string(userId)                                   // in_logged_userid
            .string(command.performanceRemarkDesc())          // in_performance_remark_desc
            .string(command.scalerPerformanceActnCode())      // in_scaler_performance_ctn_cd
            .string(command.scalerPerformanceOutcmCode())     // in_scaler_performance_tcm_cd
            .string(command.outcomeDesc())                    // in_outcome_desc
            .date(command.suspendStartDate())                 // in_suspend_start_date
            .longValue(command.checkScaleId())                // in_check_scale_id
            .date(command.suspendEndDate())                   // in_suspend_end_date
            .string(userId)                                   // in_entry_userid
            .string(userId);                                  // in_update_userid
  }

  /** Maps the single row a write procedure returns, failing loudly if the cursor is empty. */
  private PerformanceRemarkRecord requireRemarkRow(ResultSet rs) throws SQLException {
    if (rs.next()) {
      return mapRow(rs);
    }
    throw new SQLException("Stored procedure did not return a performance-remark row.");
  }

  /**
   * Deletes a performance-remark row via {@code delete_rec}, a procedure taking one IN param (the
   * PK). Mirrors the legacy {@code ScalerPerformanceRemarkDeleteAction}.
   */
  public void delete(Long scalerPerformanceRemarkId) {
    executeVoidCall(buildDeleteRecCall(PERFORMANCE_REMARK_PKG, 1),
        cs -> ParameterBinder.fromStart(cs)
            .longValue(scalerPerformanceRemarkId));  // in_scaler_performance_rmrk_d
  }

  private PerformanceRemarkRecord mapRow(ResultSet rs) throws SQLException {
    return new PerformanceRemarkRecord(
        getLongNullable(rs, "scaler_performance_remark_id"),
        rs.getString("scaler_licence_no"),
        getLocalDateNullable(rs, "logged_timestamp"),
        rs.getString("logged_userid"),
        rs.getString("performance_remark_desc"),
        rs.getString("scaler_performance_actn_code"),
        rs.getString("scaler_performance_outcm_code"),
        rs.getString("outcome_desc"),
        getLocalDateNullable(rs, "suspend_start_date"),
        getLongNullable(rs, "check_scale_id"),
        getLocalDateNullable(rs, "suspend_end_date"),
        getOffsetDateTimeNullable(rs, "entry_timestamp"),
        rs.getString("entry_userid"),
        getOffsetDateTimeNullable(rs, "update_timestamp"),
        rs.getString("update_userid"),
        getLongNullable(rs, "revision_count"));
  }
}
