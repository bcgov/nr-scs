package ca.bc.gov.nrs.scs.backend.repository;

import static ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils.currentUserIdOrSystem;

import ca.bc.gov.nrs.scs.backend.domain.appointment.ScalerAppointmentCommand;
import ca.bc.gov.nrs.scs.backend.domain.appointment.ScalerAppointmentRecord;
import ca.bc.gov.nrs.scs.backend.domain.shared.YesNo;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

@Repository
public class ScalerAppointmentRepository extends AbstractRepository {

  private static final String SCALER_LICENCE_ATTRIBT_PKG = "scs_scaler_licence_attribt_pkg";


  public ScalerAppointmentRepository(JdbcTemplate jdbcTemplate) {
    super(jdbcTemplate);
  }

  public List<ScalerAppointmentRecord> findByScalerLicenceNo(String scalerLicenceNo) {
    return search(null, scalerLicenceNo);
  }

  public ScalerAppointmentRecord findById(Long scalerLicenceAttributeId) {
    return queryCursorCall(buildSelectRecCall(SCALER_LICENCE_ATTRIBT_PKG, 1),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scalerLicenceAttributeId),
        rs -> rs.next() ? mapAppointmentRow(rs) : null);
  }

  public ScalerAppointmentRecord insert(String scalerLicenceNo, ScalerAppointmentCommand command) {
    final String userId = currentUserIdOrSystem();

    return queryCursorCall(buildInsertRecCall(SCALER_LICENCE_ATTRIBT_PKG, 12),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()                                 // in_scaler_licence_attribut_d — generated by DB
            .string(scalerLicenceNo)                       // in_scaler_licence_no
            .string(command.scalerAppointmentType())       // in_scaler_appointment_type
            .string(command.scaleGradingSystemCode())      // in_scale_grading_system_code
            .longValue(command.orgUnitNo())                // in_org_unit_no
            .string(YesNo.toCode(command.provinceWideInd())) // in_province_wide_ind
            .date(command.issuedDate())                    // in_issued_date
            .date(command.expiryDate())                    // in_expiry_date
            .nullDate()                                    // in_cancellation_date — null on insert
            .nullString()                                  // in_cancellation_reason_txt — null on insert
            .string(userId)                                // in_entry_userid
            .string(userId),                               // in_update_userid
        rs -> {
          if (rs.next()) {
            return mapAppointmentRow(rs);
          }
          throw new SQLException("Stored procedure did not return an appointment row.");
        });
  }

  public ScalerAppointmentRecord update(
      String scalerLicenceNo,
      Long scalerLicenceAttributeId,
      ScalerAppointmentCommand command
  ) {
    final String userId = currentUserIdOrSystem();

    return queryCursorCall(buildUpdateRecCall(SCALER_LICENCE_ATTRIBT_PKG, 12),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scalerLicenceAttributeId)           // in_scaler_licence_attribut_d
            .string(scalerLicenceNo)                       // in_scaler_licence_no
            .string(command.scalerAppointmentType())       // in_scaler_appointment_type
            .string(command.scaleGradingSystemCode())      // in_scale_grading_system_code
            .longValue(command.orgUnitNo())                // in_org_unit_no
            .string(YesNo.toCode(command.provinceWideInd())) // in_province_wide_ind
            .date(command.issuedDate())                    // in_issued_date
            .date(command.expiryDate())                    // in_expiry_date
            .date(command.cancellationDate())              // in_cancellation_date
            .string(command.cancellationReasonTxt())       // in_cancellation_reason_txt
            .string(userId)                                // in_entry_userid
            .string(userId),                               // in_update_userid
        rs -> {
          if (rs.next()) {
            return mapAppointmentRow(rs);
          }
          throw new SQLException("Stored procedure did not return an appointment row.");
        });
  }

  public void delete(Long scalerLicenceAttributeId) {
    executeVoidCall(buildDeleteRecCall(SCALER_LICENCE_ATTRIBT_PKG, 1),
        cs -> ParameterBinder.fromStart(cs)
            .longValue(scalerLicenceAttributeId)); // in_scaler_licence_attribut_d
  }

  private List<ScalerAppointmentRecord> search(Long scalerLicenceAttributeId, String scalerLicenceNo) {
    return queryCursorCall(buildSearchRecsCall(SCALER_LICENCE_ATTRIBT_PKG, 12),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scalerLicenceAttributeId)  // p_scaler_licence_attribut_d
            .string(scalerLicenceNo)              // p_scaler_licence_no
            .nullString()                         // p_scaler_appointment_type — not filtering
            .nullString()                         // p_scale_grading_system_code — not filtering
            .nullNumeric()                        // p_org_unit_no — not filtering
            .nullString()                         // p_province_wide_ind — not filtering
            .nullDate()                           // p_issued_date — not filtering
            .nullDate()                           // p_expiry_date — not filtering
            .nullDate()                           // p_cancellation_date — not filtering
            .nullString()                         // p_cancellation_reason_txt — not filtering
            .nullString()                         // p_entry_userid — not filtering
            .nullString(),                        // p_update_userid — not filtering
        rs -> {
          List<ScalerAppointmentRecord> appointments = new ArrayList<>();
          while (rs.next()) {
            appointments.add(mapAppointmentRow(rs));
          }
          return appointments;
        });
  }

  private ScalerAppointmentRecord mapAppointmentRow(ResultSet rs) throws SQLException {
    return new ScalerAppointmentRecord(
        getLongNullable(rs, "scaler_licence_attribute_id"),
        rs.getString("scaler_licence_no"),
        rs.getString("scaler_appointment_type"),
        rs.getString("scale_grading_system_code"),
        getLongNullable(rs, "org_unit_no"),
        YesNo.fromCode(rs.getString("province_wide_ind")),
        getLocalDateNullable(rs, "issued_date"),
        getLocalDateNullable(rs, "expiry_date"),
        getLocalDateNullable(rs, "cancellation_date"),
        rs.getString("cancellation_reason_txt"),
        getOffsetDateTimeNullable(rs, "entry_timestamp"),
        rs.getString("entry_userid"),
        getOffsetDateTimeNullable(rs, "update_timestamp"),
        rs.getString("update_userid"),
        getLongNullable(rs, "revision_count"));
  }

}
