package ca.bc.gov.nrs.scs.backend.repository;

import ca.bc.gov.nrs.scs.backend.model.ScaleSignatoryBlock;
import ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import org.openapitools.jackson.nullable.JsonNullable;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

@Repository
public class ScaleSignatoryBlockRepository extends AbstractRepository {

  private static final String SIGNATORY_SEARCH_PKG = "scs_maint_signatories_vw_pkg";
  private static final String SIGNATORY_PKG = "scs_scale_signatory_block_pkg";


  public ScaleSignatoryBlockRepository(JdbcTemplate jdbcTemplate) {
    super(jdbcTemplate);
  }

  public List<ScaleSignatoryBlock> searchSignatureBlocks(
      Long scaleSignatoryBlockId,
      Long orgUnitNo,
      Long rollupRegionNo,
      String lastName,
      String firstName,
      String middleName,
      String signatureTitle) {

    List<ScaleSignatoryBlock> results = queryCursorCall(buildSearchRecsCall(SIGNATORY_SEARCH_PKG, 12),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scaleSignatoryBlockId)
            .string(lastName)
            .string(firstName)
            .string(middleName)
            .string(signatureTitle)
            .nullString()
            .longValue(orgUnitNo)
            .nullString()
            .nullString()
            .longValue(rollupRegionNo)
            .intValue(2)
            .intValue(3),
        rs -> {
          List<ScaleSignatoryBlock> rows = new ArrayList<>();
          while (rs.next()) {
            rows.add(mapSearchRow(rs));
          }
          return rows;
        });

    return results != null ? results : List.of();
  }

  public ScaleSignatoryBlock getSignatureBlock(Long scaleSignatoryBlockId) {
    return queryCursorCall(buildSelectRecCall(SIGNATORY_PKG, 1),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scaleSignatoryBlockId),
        rs -> {
          if (rs.next()) {
            return mapDetailRow(rs);
          }
          return null;
        });
  }

  public ScaleSignatoryBlock createSignatureBlock(
      Long orgUnitNo,
      String firstName,
      String middleName,
      String lastName,
      String signatureTitle) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    return queryCursorCall(buildInsertRecCall(SIGNATORY_PKG, 8),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()                  // in_scale_signatory_block_id — generated by DB
            .longValue(orgUnitNo)
            .string(firstName)
            .string(middleName)
            .string(lastName)
            .string(signatureTitle)
            .string(userId)                 // in_entry_userid
            .string(userId),                // in_update_userid
        rs -> {
          if (rs.next()) {
            return mapDetailRow(rs);
          }
          return null;
        });
  }

  public ScaleSignatoryBlock updateSignatureBlock(
      Long scaleSignatoryBlockId,
      Long orgUnitNo,
      String firstName,
      String middleName,
      String lastName,
      String signatureTitle) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    return queryCursorCall(buildUpdateRecCall(SIGNATORY_PKG, 8),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(scaleSignatoryBlockId)
            .longValue(orgUnitNo)
            .string(firstName)
            .string(middleName)
            .string(lastName)
            .string(signatureTitle)
            .string(userId)                 // in_entry_userid
            .string(userId),                // in_update_userid
        rs -> {
          if (rs.next()) {
            return mapDetailRow(rs);
          }
          return null;
        });
  }

  public void deleteSignatureBlock(Long scaleSignatoryBlockId) {
    executeVoidCall(buildDeleteRecCall(SIGNATORY_PKG, 1),
        cs -> ParameterBinder.fromStart(cs)
            .longValue(scaleSignatoryBlockId));
  }

  private ScaleSignatoryBlock mapSearchRow(ResultSet rs) throws SQLException {
    ScaleSignatoryBlock row = new ScaleSignatoryBlock();
    row.setScaleSignatoryBlockId(getLongNullable(rs, 1));
    row.setLastName(rs.getString(2));
    row.setFirstName(rs.getString(3));
    row.setMiddleName(rs.getString(4));
    row.setSignatureTitle(rs.getString(5));
    row.setOrgUnitDescription(rs.getString(6));
    row.setOrgUnitNo(getLongNullable(rs, 7));
    row.setEntryTimestamp(JsonNullable.of(getOffsetDateTimeNullable(rs, 8)));
    row.setEntryUserid(JsonNullable.of(rs.getString(9)));
    row.setUpdateTimestamp(JsonNullable.of(getOffsetDateTimeNullable(rs, 10)));
    row.setUpdateUserid(JsonNullable.of(rs.getString(11)));
    return row;
  }

  private ScaleSignatoryBlock mapDetailRow(ResultSet rs) throws SQLException {
    ScaleSignatoryBlock row = new ScaleSignatoryBlock();
    row.setScaleSignatoryBlockId(getLongNullable(rs, 1));
    row.setOrgUnitNo(getLongNullable(rs, 2));
    row.setFirstName(rs.getString(3));
    row.setMiddleName(rs.getString(4));
    row.setLastName(rs.getString(5));
    row.setSignatureTitle(rs.getString(6));
    row.setEntryTimestamp(JsonNullable.of(getOffsetDateTimeNullable(rs, 7)));
    row.setEntryUserid(JsonNullable.of(rs.getString(8)));
    row.setUpdateTimestamp(JsonNullable.of(getOffsetDateTimeNullable(rs, 9)));
    row.setUpdateUserid(JsonNullable.of(rs.getString(10)));
    row.setRevisionCount(JsonNullable.of(getLongNullable(rs, 11)));
    return row;
  }
}
