package ca.bc.gov.nrs.scs.backend.repository;

import java.sql.Connection;
import java.sql.CallableStatement;
import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.List;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import ca.bc.gov.nrs.scs.backend.model.ScaleAuthCondition;
import ca.bc.gov.nrs.scs.backend.model.ScaleAuthConditionRef;
import ca.bc.gov.nrs.scs.backend.model.ScaleAuthTemplate;
import ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils;
import ca.bc.gov.nrs.scs.backend.util.SCSUtils;


@Repository
public class ScaleAuthTemplateRepository extends AbstractRepository {

    private static final String SCALE_AUTH_TEMPLATE_PACKAGE = "scs_scale_auth_template_pkg";
    public static final String SCALE_TEMPLATE_CONDITION_PKG = "scs_scale_template_conditn_pkg";

  private final ScalerAuthorizationRepository conditionRepository;

  public ScaleAuthTemplateRepository(JdbcTemplate jdbcTemplate,
      ScalerAuthorizationRepository conditionRepository) {
    super(jdbcTemplate);
    this.conditionRepository = conditionRepository;
  }

  public List<ScaleAuthTemplate> searchTemplates(
      String scaleConditionClassCode, Long orgUnitNo, String scaleAuthTemplateName) {
    final String classCode = SCSUtils.isBlank(scaleConditionClassCode) ? null : scaleConditionClassCode;
    final String templateName = SCSUtils.isBlank(scaleAuthTemplateName) ? null : scaleAuthTemplateName;
    List<ScaleAuthTemplate> results = queryCursorCall(buildSearchRecsCall(SCALE_AUTH_TEMPLATE_PACKAGE, 6),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()                        // p_scale_auth_template_id
            .longValue(orgUnitNo)                 // p_org_unit_no
            .string(classCode)                    // p_scale_condition_class_code
            .string(templateName)                 // p_scale_auth_template_name
            .nullString()                         // p_entry_userid
            .nullString(),                        // p_update_userid
        rs -> {
          List<ScaleAuthTemplate> out = new ArrayList<>();
          while (rs.next()) {
            out.add(mapRow(rs));
          }
          return out;
        });

    return results != null ? results : List.of();
  }

  public ScaleAuthTemplate getTemplate(Long templateId) {
    ScaleAuthTemplate template = queryCursorCall(buildSelectRecCall(SCALE_AUTH_TEMPLATE_PACKAGE, 1),
        cs -> ParameterBinder.afterReturn(cs).longValue(templateId),
        rs -> rs.next() ? mapRow(rs) : null);

    if (template == null) {
      return null;
    }

    List<ScaleAuthCondition> conditions =
        conditionRepository.getScaleAuthTemplateConditions(templateId);
    template.conditions(conditions);
    return template;
  }

  public ScaleAuthTemplate createTemplate(
      String scaleAuthTemplateName, String scaleConditionClassCode, Long orgUnitNo) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    return queryCursorCall(buildInsertRecCall(SCALE_AUTH_TEMPLATE_PACKAGE, 6),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()                        // in_scale_auth_template_id — generated by DB
            .longValue(orgUnitNo)                 // in_org_unit_no
            .string(scaleConditionClassCode)      // in_scale_condition_class_code
            .string(scaleAuthTemplateName)        // in_scale_auth_template_name
            .string(userId)                       // in_entry_userid
            .string(userId),                      // in_update_userid
        rs -> rs.next() ? mapRow(rs) : null);
  }

  public ScaleAuthTemplate updateTemplate(
      Long templateId, String scaleAuthTemplateName, String scaleConditionClassCode, Long orgUnitNo) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    return queryCursorCall(buildUpdateRecCall(SCALE_AUTH_TEMPLATE_PACKAGE, 6),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(templateId)                // in_scale_auth_template_id
            .longValue(orgUnitNo)                 // in_org_unit_no
            .string(scaleConditionClassCode)      // in_scale_condition_class_code
            .string(scaleAuthTemplateName)        // in_scale_auth_template_name
            .string(userId)                       // in_entry_userid
            .string(userId),                      // in_update_userid
        rs -> rs.next() ? mapRow(rs) : null);
  }

  public void deleteTemplate(Long templateId) {
    deleteAllTemplateConditions(templateId);
    executeVoidCall(buildDeleteRecCall(SCALE_AUTH_TEMPLATE_PACKAGE, 1),
        cs -> ParameterBinder.fromStart(cs).longValue(templateId));
  }

  public void replaceConditions(Long templateId, List<ScaleAuthConditionRef> conditions) {
    deleteAllTemplateConditions(templateId);
    addConditions(templateId, conditions);
  }

  public void addConditions(Long templateId, List<ScaleAuthConditionRef> conditions) {
    if (conditions == null || conditions.isEmpty()) {
      return;
    }

    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    for (ScaleAuthConditionRef ref : conditions) {
      if (!isValidConditionRef(ref)) {
        continue;
      }

      queryCursorCall(buildInsertRecCall(SCALE_TEMPLATE_CONDITION_PKG, 5),
          cs -> ParameterBinder.afterReturn(cs)
              .longValue(templateId)                    // in_scale_auth_template_id
              .string(ref.getScaleConditionClassCode()) // in_scale_condition_class_code
              .longValue(ref.getScaleAuthConditionId()) // in_scale_auth_condition_id
              .string(userId)                           // in_entry_userid
              .string(userId),                          // in_update_userid
          rs -> null);
    }
  }

  private void deleteAllTemplateConditions(Long templateId) {
    List<ConditionRef> refs = searchConditionRefs(templateId);
    deleteConditions(refs);
  }

  private boolean isValidConditionRef(ScaleAuthConditionRef ref) {
    return ref != null && ref.getScaleAuthConditionId() != null;
  }

  private List<ConditionRef> searchConditionRefs(Long templateId) {
    List<ConditionRef> refs = queryCursorCall(buildSearchRecsCall(SCALE_TEMPLATE_CONDITION_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .longValue(templateId)  // p_scale_auth_template_id
            .nullString()           // p_scale_condition_class_code — not filtering
            .nullNumeric()          // p_scale_auth_condition_id — not filtering
            .nullString()           // p_entry_userid — not filtering
            .nullString(),          // p_update_userid — not filtering
        rs -> {
          List<ConditionRef> out = new ArrayList<>();
          while (rs.next()) {
            Long tid = getLongNullable(rs, "scale_auth_template_id");
            String cc = rs.getString("scale_condition_class_code");
            Long cid = getLongNullable(rs, "scale_auth_condition_id");
            if (tid != null && cid != null) {
              out.add(new ConditionRef(tid, cc, cid));
            }
          }
          return out;
        });

    return refs != null ? refs : List.of();
  }

    private void deleteConditions(List<ConditionRef> refs) {
    if (refs.isEmpty()) {
      return;
    }
    getJdbcTemplate().execute((Connection con) -> {
        try (CallableStatement cs = con.prepareCall(buildDeleteRecCall(SCALE_TEMPLATE_CONDITION_PKG, 3))) {
          Long templateId = refs.get(0).templateId();
          for (ConditionRef ref : refs) {
            // delete_rec is a batch: rebind every row from the start index before addBatch().
            ParameterBinder.fromStart(cs)
                .longValue(templateId)
                .string(ref.classCode())
                .longValue(ref.conditionId());
            cs.addBatch();
          }
          cs.executeBatch();
      }
      return null;
    });
  }

  private ScaleAuthTemplate mapRow(ResultSet rs) throws java.sql.SQLException {
    return new ScaleAuthTemplate()
        .scaleAuthTemplateId(getLongNullable(rs, "scale_auth_template_id"))
        .orgUnitNo(getLongNullable(rs, "org_unit_no"))
        .scaleConditionClassCode(rs.getString("scale_condition_class_code"))
        .scaleAuthTemplateName(rs.getString("scale_auth_template_name"))
        .entryTimestamp(getOffsetDateTimeNullable(rs, "entry_timestamp"))
        .entryUserid(rs.getString("entry_userid"))
        .updateTimestamp(getOffsetDateTimeNullable(rs, "update_timestamp"))
        .updateUserid(rs.getString("update_userid"))
        .revisionCount(getLongNullable(rs, "revision_count"));
  }

  private record ConditionRef(Long templateId, String classCode, Long conditionId) {}
}
