package ca.bc.gov.nrs.scs.backend.repository;

import ca.bc.gov.nrs.scs.backend.model.ScaleAuthConditionCreateRequest;
import ca.bc.gov.nrs.scs.backend.model.ScaleAuthConditionDetail;
import ca.bc.gov.nrs.scs.backend.model.ScaleAuthConditionUpdateRequest;
import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Types;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;
import ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils;


@Repository
public class ConditionRepository extends AbstractRepository {

  private static final String SCALER_AUTH_CONDITION_PKG = "scs_scale_auth_condition_pkg";
  private static final String SCALER_MTHD_CONDITION_PKG = "scs_scale_mthd_condition_pkg";
  private static final String SCALER_AUTHZTN_CNDTN_PKG = "scs_scaler_authorztn_cndtn_pkg";
  private static final String SITE_AUTHORIZATN_CNDTN_PKG = "scs_site_authorizatn_cndtn_pkg";
  private static final String SCALE_TEMPLATE_CONDITN_PKG = "scs_scale_template_conditn_pkg";
  private static final String HAULING_MARK_SIT_CNDTN_PKG = "scs_hauling_mark_sit_cndtn_pkg";


  public ConditionRepository(JdbcTemplate jdbcTemplate) {
    super(jdbcTemplate);
  }


  public List<ScaleAuthConditionDetail> searchConditions(
      String scaleConditionClassCode,
      Long scaleAuthConditionId,
      String scaleAuthConditionTitle,
      String scaleAuthConditionDesc,
      String ministryStandardInd,
      Integer sortOrderNo,
      LocalDate effectiveDate,
      LocalDate expiryDate) {

    List<ScaleAuthConditionDetail> results = queryCursorCall(
        buildSearchRecsCall(SCALER_AUTH_CONDITION_PKG, 10),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId)
            .string(scaleAuthConditionTitle)
            .string(scaleAuthConditionDesc)
            .string(ministryStandardInd)
            .intValue(sortOrderNo)
            .date(effectiveDate)
            .date(expiryDate)
            .nullString()   // p_entry_userid — not filtering
            .nullString(),  // p_update_userid — not filtering
        rs -> {
          List<ScaleAuthConditionDetail> rows = new ArrayList<>();
          while (rs.next()) {
            rows.add(mapConditionRow(rs));
          }
          return rows;
        });

    if (results == null || results.isEmpty()) {
      results = List.of();
    }

    boolean needsMethods = results.stream()
        .anyMatch(row -> "SIA".equalsIgnoreCase(row.getScaleConditionClassCode()));
    if (!needsMethods) {
      return results;
    }

    Map<Long, List<String>> methodMap = fetchScaleMethodTypeCodes("SIA", null);
    for (ScaleAuthConditionDetail condition : results) {
      if (!"SIA".equalsIgnoreCase(condition.getScaleConditionClassCode())) {
        continue;
      }
      condition.setSiteMethodTypeCodes(methodMap.getOrDefault(condition.getScaleAuthConditionId(), List.of()));
    }

    return results;
  }

  public ScaleAuthConditionDetail getCondition(String scaleConditionClassCode, Long scaleAuthConditionId) {
    ScaleAuthConditionDetail condition = queryCursorCall(
        buildSelectRecCall(SCALER_AUTH_CONDITION_PKG, 2),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId),
        rs -> rs.next() ? mapConditionRow(rs) : null);

    if (condition == null) {
      return null;
    }

    if ("SIA".equalsIgnoreCase(scaleConditionClassCode)) {
      List<String> codes = fetchScaleMethodTypeCodes(scaleConditionClassCode, scaleAuthConditionId)
          .getOrDefault(scaleAuthConditionId, List.of());
      condition.setSiteMethodTypeCodes(codes);
    } else {
      condition.setSiteMethodTypeCodes(List.of());
    }

    condition.setDependentChildExists(hasDependentChildren(scaleConditionClassCode, scaleAuthConditionId));
    return condition;
  }

  public ScaleAuthConditionDetail createCondition(ScaleAuthConditionCreateRequest request) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    ScaleAuthConditionDetail created = queryCursorCall(
        buildInsertRecCall(SCALER_AUTH_CONDITION_PKG, 10),
        cs -> ParameterBinder.afterReturn(cs)
            .string(request.getScaleConditionClassCode())
            .nullNumeric()                                // in_scale_auth_condition_id — generated by DB
            .string(request.getScaleAuthConditionTitle())
            .string(request.getScaleAuthConditionDesc())
            .string(request.getMinistryStandardInd())
            .intValue(request.getSortOrderNo())
            .date(request.getEffectiveDate())
            .date(request.getExpiryDate())
            .string(userId)                               // in_entry_userid
            .string(userId),                              // in_update_userid
        rs -> rs.next() ? mapConditionRow(rs) : null);

    if (created == null) {
      return null;
    }

    updateMethodTypes(created.getScaleConditionClassCode(), created.getScaleAuthConditionId(),
        List.of(), request.getSiteMethodTypeCodes(), userId);

    created.setSiteMethodTypeCodes(request.getSiteMethodTypeCodes());
    created.setDependentChildExists(false);
    return created;
  }

  public ScaleAuthConditionDetail updateCondition(
      String scaleConditionClassCode,
      Long scaleAuthConditionId,
      ScaleAuthConditionUpdateRequest request) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();

    ScaleAuthConditionDetail updated = queryCursorCall(
        buildUpdateRecCall(SCALER_AUTH_CONDITION_PKG, 10),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId)
            .string(request.getScaleAuthConditionTitle())
            .string(request.getScaleAuthConditionDesc())
            .string(request.getMinistryStandardInd())
            .intValue(request.getSortOrderNo())
            .date(request.getEffectiveDate())
            .date(request.getExpiryDate())
            .string(userId)                               // in_entry_userid
            .string(userId),                              // in_update_userid
        rs -> rs.next() ? mapConditionRow(rs) : null);

    if (updated == null) {
      return null;
    }

    List<String> existingCodes = fetchScaleMethodTypeCodes(scaleConditionClassCode, scaleAuthConditionId)
        .getOrDefault(scaleAuthConditionId, List.of());
    updateMethodTypes(scaleConditionClassCode, scaleAuthConditionId, existingCodes,
        request.getSiteMethodTypeCodes(), userId);

    updated.setSiteMethodTypeCodes(request.getSiteMethodTypeCodes());
    updated.setDependentChildExists(hasDependentChildren(scaleConditionClassCode, scaleAuthConditionId));
    return updated;
  }

  public boolean deleteCondition(String scaleConditionClassCode, Long scaleAuthConditionId) {
    final String userId = SecurityContextUtils.currentUserIdOrSystem();
    List<String> existingCodes = fetchScaleMethodTypeCodes(scaleConditionClassCode, scaleAuthConditionId)
        .getOrDefault(scaleAuthConditionId, List.of());
    updateMethodTypes(scaleConditionClassCode, scaleAuthConditionId, existingCodes, List.of(), userId);

    executeVoidCall(buildDeleteRecCall(SCALER_AUTH_CONDITION_PKG, 2),
        cs -> ParameterBinder.fromStart(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId));

    return true;
  }

  private void updateMethodTypes(
      String scaleConditionClassCode,
      Long scaleAuthConditionId,
      List<String> existingCodes,
      List<String> nextCodes,
      String userId) {
    if (!"SIA".equalsIgnoreCase(scaleConditionClassCode)) {
      for (String code : existingCodes == null ? List.<String>of() : existingCodes) {
        deleteMethodType(scaleConditionClassCode, scaleAuthConditionId, code);
      }
      return;
    }

    Set<String> existing = new HashSet<>(existingCodes == null ? List.of() : existingCodes);
    Set<String> incoming = new HashSet<>(nextCodes == null ? List.of() : nextCodes);

    for (String code : existing) {
      if (!incoming.contains(code)) {
        deleteMethodType(scaleConditionClassCode, scaleAuthConditionId, code);
      }
    }

    for (String code : incoming) {
      if (!existing.contains(code)) {
        insertMethodType(scaleConditionClassCode, scaleAuthConditionId, code, userId);
      }
    }
  }

  private void insertMethodType(String scaleConditionClassCode, Long scaleAuthConditionId, String methodCode, String userId) {
    if (methodCode == null || methodCode.isBlank()) {
      return;
    }

    queryCursorCall(buildInsertRecCall(SCALER_MTHD_CONDITION_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId)
            .string(methodCode)
            .string(userId)   // in_entry_userid
            .string(userId),  // in_update_userid
        rs -> null);
  }

  private void deleteMethodType(String scaleConditionClassCode, Long scaleAuthConditionId, String methodCode) {
    if (methodCode == null || methodCode.isBlank()) {
      return;
    }

    executeVoidCall(buildDeleteRecCall(SCALER_MTHD_CONDITION_PKG, 3),
        cs -> ParameterBinder.fromStart(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId)
            .string(methodCode));
  }

  private Map<Long, List<String>> fetchScaleMethodTypeCodes(String scaleConditionClassCode, Long scaleAuthConditionId) {
    Map<Long, List<String>> result = queryCursorCall(
        buildSearchRecsCall(SCALER_MTHD_CONDITION_PKG, 5),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scaleConditionClassCode)
            .longValue(scaleAuthConditionId)
            .nullString()   // p_scale_method_type_code — not filtering
            .nullString()   // p_entry_userid — not filtering
            .nullString(),  // p_update_userid — not filtering
        rs -> {
          Map<Long, List<String>> results = new HashMap<>();
          while (rs.next()) {
            Long conditionId = getLongNullable(rs, "scale_auth_condition_id");
            String methodCode = rs.getString("scale_method_type_code");
            if (conditionId == null || methodCode == null) {
              continue;
            }
            results.computeIfAbsent(conditionId, key -> new ArrayList<>()).add(methodCode);
          }
          return results;
        });
    return result != null ? result : Map.of();
  }

  private boolean hasDependentChildren(String scaleConditionClassCode, Long scaleAuthConditionId) {
    if (scaleAuthConditionId == null) {
      return false;
    }

    int scalerCount = countConditionRefs(buildCountRecsCall(SCALER_AUTHZTN_CNDTN_PKG, 5), scaleConditionClassCode, scaleAuthConditionId);
    int siteCount = countConditionRefs(buildCountRecsCall(SITE_AUTHORIZATN_CNDTN_PKG, 5), scaleConditionClassCode, scaleAuthConditionId);
    int templateCount = countConditionRefs(buildCountRecsCall(SCALE_TEMPLATE_CONDITN_PKG, 5), scaleConditionClassCode, scaleAuthConditionId);
    int haulingCount = countConditionRefs(buildCountRecsCall(HAULING_MARK_SIT_CNDTN_PKG, 5), scaleConditionClassCode, scaleAuthConditionId);

    return scalerCount > 0 || siteCount > 0 || templateCount > 0 || haulingCount > 0;
  }

  private int countConditionRefs(String sql, String scaleConditionClassCode, Long scaleAuthConditionId) {
    Integer count = getJdbcTemplate().execute(
        (Connection con) -> {
          CallableStatement cs = con.prepareCall(sql);
          cs.registerOutParameter(1, Types.NUMERIC);
          ParameterBinder.afterReturn(cs)
              .nullNumeric()                       // p_unused numeric filter
              .string(scaleConditionClassCode)
              .longValue(scaleAuthConditionId)
              .nullString()
              .nullString();
          return cs;
        },
        (CallableStatement cs) -> {
          cs.execute();
          Object value = cs.getObject(1);
          if (value instanceof Number number) {
            return number.intValue();
          }
          return 0;
        });

    return count == null ? 0 : count;
  }

  private ScaleAuthConditionDetail mapConditionRow(ResultSet rs) throws java.sql.SQLException {
    ScaleAuthConditionDetail condition = new ScaleAuthConditionDetail();
    condition.setScaleConditionClassCode(rs.getString("scale_condition_class_code"));
    condition.setScaleAuthConditionId(getLongNullable(rs, "scale_auth_condition_id"));
    condition.setScaleAuthConditionTitle(rs.getString("scale_auth_condition_title"));
    condition.setScaleAuthConditionDesc(rs.getString("scale_auth_condition_desc"));
    condition.setMinistryStandardInd(rs.getString("ministry_standard_ind"));
    condition.setSortOrderNo(getIntNullable(rs, "sort_order_no"));
    condition.setEffectiveDate(getLocalDateNullable(rs, "effective_date"));
    condition.setExpiryDate(getLocalDateNullable(rs, "expiry_date"));
    condition.setEntryTimestamp(getOffsetDateTimeNullable(rs, "entry_timestamp"));
    condition.setEntryUserid(rs.getString("entry_userid"));
    condition.setUpdateTimestamp(getOffsetDateTimeNullable(rs, "update_timestamp"));
    condition.setUpdateUserid(rs.getString("update_userid"));
    condition.setRevisionCount(getLongNullable(rs, "revision_count"));
    return condition;
  }
}
