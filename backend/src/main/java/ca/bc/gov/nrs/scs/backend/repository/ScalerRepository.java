  /**
   * Updates the core scaler row and reconciles assigned licence types.
   * {@code persistedLicenceCancelledDate} is bound instead of anything from the command — the
   * cancel date is read-only via the general update (owned by {@link #updateLicenceCancelledDate}).
   */
  public void updateScaler(ScalerUpdateCommand cmd, LocalDate persistedLicenceCancelledDate) {
    final String userId = currentUserIdOrSystem();
    queryCursorCall(buildUpdateRecCall(SCALER_PKG, 9),
        cs -> ParameterBinder.afterReturn(cs)
            .string(cmd.scalerLicenceNo())            // in_scaler_licence_no
            .string(cmd.clientNumber())               // in_client_number
            .longValue(cmd.orgUnitNo())               // in_org_unit_no
            .date(cmd.issuedDate())                   // in_issued_date
            .date(cmd.expiryDate())                   // in_expiry_date
            .string(YesNo.toCode(cmd.oathTakenInd())) // in_oath_taken_ind
            .date(persistedLicenceCancelledDate)      // in_licence_cancelled_date — carried forward
            .string(userId)                           // in_entry_userid (required by signature)
            .string(userId),                          // in_update_userid
        rs -> null); // cursor returned but not needed — ScalerService reloads after orchestration

    // 2. Reconcile licence types — add missing, remove unchecked
    for (ScalerLicenceType type : List.of(ScalerLicenceType.SCS, ScalerLicenceType.WA)) {
      if (cmd.licenceTypes().contains(type)) {
        createAssignedLicTypeIfAbsent(cmd.scalerLicenceNo(), type.name());
      } else {
        deleteAssignedLicTypeIfPresent(cmd.scalerLicenceNo(), type.name());
      }
    }
  }

  /**
   * Sets (or clears) only the scaler's licence cancelled date, preserving every other column.
   * Mirrors the legacy {@code ScalerPerformanceRemarkSummaryAction.cancelScaler} flow, which loads
   * the full scaler and re-runs {@code scs_scaler_pkg.update_rec} (the whole row is rewritten). The
   * current column values are read back verbatim via {@code select_rec} so no value (e.g. the
   * unpadded client number) is inadvertently changed. Returns {@code null} if the scaler is absent.
   */
  public Scaler updateLicenceCancelledDate(String scalerLicenceNo, LocalDate licenceCancelledDate) {
    ScalerCoreWriteRow current = queryCursorCall(buildSelectRecCall(SCALER_PKG, 1),
        cs -> cs.setString(2, scalerLicenceNo),
        rs -> rs.next()
            ? new ScalerCoreWriteRow(
                rs.getString("client_number"),
                getLongNullable(rs, "org_unit_no"),
                getLocalDateNullable(rs, COL_ISSUED_DATE),
                getLocalDateNullable(rs, COL_EXPIRY_DATE),
                rs.getString("oath_taken_ind"))
            : null);

    if (current == null) {
      return null;
    }

    final String userId = currentUserIdOrSystem();
    queryCursorCall(buildUpdateRecCall(SCALER_PKG, 9),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scalerLicenceNo)          // in_scaler_licence_no
            .string(current.clientNumber())   // in_client_number (raw, unpadded)
            .longValue(current.orgUnitNo())   // in_org_unit_no
            .date(current.issuedDate())       // in_issued_date
            .date(current.expiryDate())       // in_expiry_date
            .string(current.oathTakenInd())   // in_oath_taken_ind
            .date(licenceCancelledDate)       // in_licence_cancelled_date
            .string(userId)                   // in_entry_userid (required by signature)
            .string(userId),                  // in_update_userid
        rs -> null);

    return getScaler(scalerLicenceNo);
  }

