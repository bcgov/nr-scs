  /**
   * The licence numbers of every scaler belonging to a forest client, for access decisions. Reads
   * {@code scs_scaler_vw_pkg} ({@code scaler} + {@code org_unit}) — the one source that sees them all.
   *
   * <p><b>Not {@link #searchScalers}</b>: its {@code scs_queries_scalars_vw} inner-joins eleven tables
   * (training, licence type, licence attributes, appointment type, client location), so a scaler missing
   * any one vanishes — it returned 5 of 776 on the seeded data. An invisible scaler reads as "this client
   * has none", ignoring every authorization they hold.
   */
  public Set<String> listLicenceNumbersForClient(String clientNumber) {
    return queryCursorCall(buildSearchRecsCall(SCALER_VW_PKG, 11),
        cs -> ParameterBinder.afterReturn(cs)
            .nullString()                             // p_scaler_licence_no
            .string(padClientNumber(clientNumber))    // p_client_number
            .nullString()    // p_org_unit_name
            .nullDate()      // p_issued_date
            .nullDate()      // p_expiry_date
            .nullString()    // p_oath_taken_ind
            .nullDate()      // p_licence_cancelled_date
            .nullString()    // p_entry_userid
            .nullString()    // p_update_userid
            .intValue(1)     // p_primary_sort
            .intValue(2),    // p_secondary_sort
        rs -> {
          Set<String> licences = new LinkedHashSet<>();
          while (rs != null && rs.next()) {
            String licence = trimToNull(rs.getString(COL_SCALER_LICENCE_NO));
            if (licence != null) {
              licences.add(licence);
            }
          }
          return licences;
        });
  }

