  private void createAssignedLicTypeIfAbsent(String licNo, String typeCode) {
    if (!assignedLicTypeExists(licNo, typeCode)) {
      insertAssignedLicType(licNo, typeCode);
    }
  }

  public void deleteAssignedLicTypeIfPresent(String licNo, String typeCode) {
    if (assignedLicTypeExists(licNo, typeCode)) {
      // delete_rec is a procedure ({ call ... }), so IN params start at index 1.
      executeVoidCall(buildDeleteRecCall(SCALER_ASSIGND_LIC_TYP_PKG, 2),
          cs -> ParameterBinder.fromStart(cs)
              .string(licNo)
              .string(typeCode));
    }
  }

  private boolean assignedLicTypeExists(String licNo, String typeCode) {
    // search_recs: (p_scaler_licence_no, p_scaler_licence_type_code, p_entry_userid, p_update_userid)
    Boolean exists = queryCursorCall(buildSearchRecsCall(SCALER_ASSIGND_LIC_TYP_PKG, 4),
        cs -> ParameterBinder.afterReturn(cs)
            .string(licNo)
            .string(typeCode)
            .nullString()   // p_entry_userid — not filtering
            .nullString(),  // p_update_userid — not filtering
        ResultSet::next);
    return Boolean.TRUE.equals(exists);
  }

