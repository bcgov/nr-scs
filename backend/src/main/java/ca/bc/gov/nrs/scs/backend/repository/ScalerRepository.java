  public String insertScaler(ScalerCreateCommand cmd) {
    final String userId = currentUserIdOrSystem();
    return queryCursorCall(buildInsertRecCall(SCALER_PKG, 9),
        cs -> ParameterBinder.afterReturn(cs)
            .nullString()                             // in_scaler_licence_no — generated by DB
            .string(cmd.clientNumber())               // in_client_number
            .longValue(cmd.orgUnitNo())               // in_org_unit_no
            .date(cmd.issuedDate())                   // in_issued_date
            .date(cmd.expiryDate())                   // in_expiry_date
            .string(YesNo.toCode(cmd.oathTakenInd())) // in_oath_taken_ind
            .date(cmd.licenceCancelledDate())         // in_licence_cancelled_date
            .string(userId)                           // in_entry_userid
            .string(userId),                          // in_update_userid
        rs -> rs.next() ? rs.getString(COL_SCALER_LICENCE_NO) : null);
  }

  /**
   * Deletes the core scaler row via {@code scs_scaler_pkg.delete_rec} (procedure, single IN param —
   * verified against {@code scs_scaler_pkg.pks:67}). The scaler's intrinsic sub-records
   * (assigned licence types, appointment, exam) are cleared first by {@link ca.bc.gov.nrs.scs.backend.service.ScalerService};
   * dependent records the cascade does not clear raise {@code ORA-02292} here.
   */
  public void deleteScaler(String scalerLicenceNo) {
    executeVoidCall(buildDeleteRecCall(SCALER_PKG, 1),
        cs -> ParameterBinder.fromStart(cs)
            .string(scalerLicenceNo)); // in_scaler_licence_no
  }

  public Scaler getScaler(String scalerLicenceNo) {
    CoreScalerRow core = queryCursorCall(buildSelectRecCall(SCALER_PKG, 1),
        cs -> cs.setString(2, scalerLicenceNo),
        rs -> rs.next() ? mapCoreScalerRow(rs) : null);

    if (core == null) {
      return null;
    }

    // 2. Load assigned licence types — scs_scaler_assignd_lic_typ_pkg.search_recs
    //    (p_scaler_licence_no, p_scaler_licence_type_code, p_entry_userid, p_update_userid)
    List<ScalerLicenceType> licTypes = queryCursorCall(
        buildSearchRecsCall(SCALER_ASSIGND_LIC_TYP_PKG, 4),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scalerLicenceNo)
            .nullString()   // p_scaler_licence_type_code — return all types
            .nullString()   // p_entry_userid — not filtering
            .nullString(),  // p_update_userid — not filtering
        rs -> {
          List<ScalerLicenceType> types = new ArrayList<>();
          while (rs.next()) {
            ScalerLicenceType type = ScalerLicenceType.fromCode(rs.getString("scaler_licence_type_code"));
            if (type != null) types.add(type);
          }
          return types;
        });

    // 3. Load appointment — scs_scaler_licence_attribt_pkg.search_recs
    //    Params: (attributeId, licenceNo, appointmentType, gradingSystemCode, orgUnitNo,
    //             provinceWideInd, issuedDate, expiryDate, cancellationDate,
    //             cancellationReasonTxt, entryUserid, updateUserid)
    ScalerAppointmentRecord appt = queryCursorCall(
        buildSearchRecsCall(SCALER_LICENCE_ATTRIBT_PKG, 12),
        cs -> ParameterBinder.afterReturn(cs)
            .nullNumeric()           // p_scaler_licence_attribut_d — not filtering
            .string(scalerLicenceNo)
            .nullString()            // p_scaler_appointment_type — not filtering
            .nullString()            // p_scale_grading_system_code — not filtering
            .nullNumeric()           // p_org_unit_no — not filtering
            .nullString()            // p_province_wide_ind — not filtering
            .nullDate()              // p_issued_date — not filtering
            .nullDate()              // p_expiry_date — not filtering
            .nullDate()              // p_cancellation_date — not filtering
            .nullString()            // p_cancellation_reason_txt — not filtering
            .nullString()            // p_entry_userid — not filtering
            .nullString(),           // p_update_userid — not filtering
        rs -> rs.next() ? mapAppointmentRow(rs) : null);

    // 4. Load exam only when no appointment (legacy: appointment wins) —
    //    scs_scaler_training_pkg.search_recs
    //    Params: (licenceNo, trainingClassCode, trainingTypeId, completionDate, entryUserid, updateUserid)
    ScalerExamRecord exam = appt != null ? null : queryCursorCall(
        buildSearchRecsCall(SCALER_TRAINING_PKG, 6),
        cs -> ParameterBinder.afterReturn(cs)
            .string(scalerLicenceNo)
            .nullString()    // p_scaler_training_class_code — not filtering
            .nullString()    // p_scaler_training_type_id — not filtering
            .nullDate()      // p_completion_date — not filtering
            .nullString()    // p_entry_userid — not filtering
            .nullString(),   // p_update_userid — not filtering
        rs -> rs.next() ? mapExamRow(rs) : null);

    return new Scaler(
        core.scalerLicenceNo(),
        core.clientNumber(),
        core.orgUnitNo(),
        core.issuedDate(),
        core.expiryDate(),
        core.oathTakenInd(),
        core.licenceCancelledDate(),
        licTypes,
        appt,
        exam,
        core.entryTimestamp(),
        core.entryUserid(),
        core.updateTimestamp(),
        core.updateUserid(),
        core.revisionCount());
  }

