package ca.bc.gov.nrs.scs.backend.repository;


import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.List;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import ca.bc.gov.nrs.scs.backend.dto.ScaleMethodAuthClauseRow;
import ca.bc.gov.nrs.scs.backend.model.ScaleMethodAuthClauseCreateRequest;
import ca.bc.gov.nrs.scs.backend.model.ScaleMethodAuthClauseUpdateRequest;
import ca.bc.gov.nrs.scs.backend.security.SecurityContextUtils;

/**
 * Repository for Scale Method Authorization Clause operations.
 * Interacts with the database using stored procedures.
 */
@Repository
public class AuthorizationClauseRepository extends AbstractRepository {

    private static final String AUTH_CLAUSE_PKG = "scs_scale_methd_auth_claus_pkg";


    public AuthorizationClauseRepository(JdbcTemplate jdbcTemplate) {
        super(jdbcTemplate);
    }

    /**
     * Search for authorization clauses.
     *
     * @param scaleMethodTypeCode Optional filter by scale method type code
     * @return List of matching authorization clauses
     */
    public List<ScaleMethodAuthClauseRow> searchAuthorizationClauses(String scaleMethodTypeCode) {
        return queryCursorCall(buildSearchRecsCall(AUTH_CLAUSE_PKG, 7),
                cs -> ParameterBinder.afterReturn(cs)
                    .nullNumeric()                      // p_scale_method_auth_claus_d — not filtering
                    .string(scaleMethodTypeCode)        // p_scale_method_type_code
                    .nullString()                       // p_scaler_authorization_clas — not filtering
                    .nullDate()                         // p_effective_date — not filtering
                    .nullDate()                         // p_expiry_date — not filtering
                    .nullString()                       // p_entry_userid — not filtering
                    .nullString(),                      // p_update_userid — not filtering
                rs -> {
                    List<ScaleMethodAuthClauseRow> rows = new ArrayList<>();
                    while (rs.next()) {
                        rows.add(mapAuthClauseRow(rs));
                    }
                    return rows;
                });
    }

    /**
     * Get a specific authorization clause.
     *
     * @param scaleMethodTypeCode     The scale method type code
     * @param scaleMethodAuthClauseId The authorization clause ID
     * @return The authorization clause detail, or null if not found
     */
    public ScaleMethodAuthClauseRow getAuthorizationClause(
            String scaleMethodTypeCode, Long scaleMethodAuthClauseId) {
        return queryCursorCall(buildSelectRecCall(AUTH_CLAUSE_PKG, 1),
                cs -> ParameterBinder.afterReturn(cs)
                    .longValue(scaleMethodAuthClauseId),
                rs -> rs.next() ? mapAuthClauseRow(rs) : null);
    }

    /**
     * Create a new authorization clause.
     *
     * @param request The create request
     * @return The created authorization clause
     */
    public ScaleMethodAuthClauseRow createAuthorizationClause(
            ScaleMethodAuthClauseCreateRequest request) {
        final String userId = SecurityContextUtils.currentUserIdOrSystem();
        return queryCursorCall(buildInsertRecCall(AUTH_CLAUSE_PKG, 7),
                cs -> ParameterBinder.afterReturn(cs)
                    .nullNumeric()                                        // in_scale_method_auth_claus_d — generated by DB
                    .string(request.getScaleMethodTypeCode())             // in_scale_method_type_code
                    .string(request.getScalerAuthorizationClause())       // in_scaler_authorization_clas
                    .date(request.getEffectiveDate())                     // in_effective_date
                    .date(request.getExpiryDate())                        // in_expiry_date
                    .string(userId)                                       // in_entry_userid
                    .string(userId),                                      // in_update_userid
                rs -> rs.next() ? mapAuthClauseRow(rs) : null);
    }

    /**
     * Update an existing authorization clause.
     *
     * @param scaleMethodTypeCode     The scale method type code
     * @param scaleMethodAuthClauseId The authorization clause ID
     * @param request                 The update request
     * @return The updated authorization clause
     */
    public ScaleMethodAuthClauseRow updateAuthorizationClause(
            String scaleMethodTypeCode,
            Long scaleMethodAuthClauseId,
            ScaleMethodAuthClauseUpdateRequest request) {
        final String userId = SecurityContextUtils.currentUserIdOrSystem();
        return queryCursorCall(buildUpdateRecCall(AUTH_CLAUSE_PKG, 7),
                cs -> ParameterBinder.afterReturn(cs)
                    .longValue(scaleMethodAuthClauseId)                   // in_scale_method_auth_claus_d
                    .string(request.getScaleMethodTypeCode())             // in_scale_method_type_code
                    .string(request.getScalerAuthorizationClause())       // in_scaler_authorization_clas
                    .date(request.getEffectiveDate())                     // in_effective_date
                    .date(request.getExpiryDate())                        // in_expiry_date
                    .string(userId)                                       // in_entry_userid
                    .string(userId),                                      // in_update_userid
                rs -> rs.next() ? mapAuthClauseRow(rs) : null);
    }

    /**
     * Delete an authorization clause.
     *
     * @param scaleMethodTypeCode     The scale method type code
     * @param scaleMethodAuthClauseId The authorization clause ID
     */
    public void deleteAuthorizationClause(String scaleMethodTypeCode, Long scaleMethodAuthClauseId) {
        executeVoidCall(buildDeleteRecCall(AUTH_CLAUSE_PKG, 1),
            cs -> ParameterBinder.fromStart(cs)
                .longValue(scaleMethodAuthClauseId));
    }

    /**
     * Map a ResultSet row to a ScaleMethodAuthClauseRow object.
     *
     * @param rs The ResultSet
     * @return The mapped object
     */
    private ScaleMethodAuthClauseRow mapAuthClauseRow(ResultSet rs) throws java.sql.SQLException {
        ScaleMethodAuthClauseRow row = new ScaleMethodAuthClauseRow();
        row.setScaleMethodAuthClauseId(getLongNullable(rs, "SCALE_METHOD_AUTH_CLAUSE_ID"));
        row.setScaleMethodTypeCode(rs.getString("SCALE_METHOD_TYPE_CODE"));
        row.setScalerAuthorizationClause(rs.getString("SCALER_AUTHORIZATION_CLAUSE"));
        row.setEffectiveDate(getLocalDateNullable(rs, "EFFECTIVE_DATE"));
        row.setExpiryDate(getLocalDateNullable(rs, "EXPIRY_DATE"));
        row.setEntryTimestamp(getOffsetDateTimeNullable(rs, "ENTRY_TIMESTAMP"));
        row.setEntryUserid(rs.getString("ENTRY_USERID"));
        row.setUpdateTimestamp(getOffsetDateTimeNullable(rs, "UPDATE_TIMESTAMP"));
        row.setUpdateUserid(rs.getString("UPDATE_USERID"));
        row.setRevisionCount(getLongNullable(rs, "REVISION_COUNT"));
        return row;
    }
}