import { type Page, type Locator, expect } from '@playwright/test';

import { loginAsMockScsUser, clientSideNavigate } from '../common/authNav';
import { fillScaleSiteFields, type ScaleSiteFormInput } from './scaleSiteFormFields';
import {
  validOwner,
  validScaleSite,
  regDistOrgUnitNo,
  primaryMethodCode,
  secondaryMethodCode,
} from '../../fixtures/sst/scale-site-test-data';

// Re-exported so existing imports (`./ScaleSiteCreatePage`) keep resolving after the fill logic moved
// to the shared scaleSiteFormFields module.
export type { Dms, ScaleSiteFormInput } from './scaleSiteFormFields';

/**
 * Page object for the Scale Site CREATE screen (route /scale-sites/create, pages/Create/ScaleSite ->
 * components/Form/ScaleSiteForm). All DOM selectors for scale-site create live here; steps call these.
 *
 * Field ids are the form's stable Carbon ids (ScaleSiteForm index.tsx): #scale-site-name, the embedded
 * ClientLocSearch inputs #client (owner) / #loc, DistrictSelect #reg-dist (native <select>), #timber-brand,
 * the DmsInput parts #latitude-degrees/-minutes/-seconds and #longitude-*, the #site-location-description
 * textarea, and the Site Type <select>s #site-type-primary/-secondary/-tertiary. The ONLY write
 * (POST /api/scale-sites) fires from "Save Record"; the form validates required/duplicate/timber/coordinate
 * rules CLIENT-side and does not POST when they fail. On success the app navigates to /scale-sites/view/{id}.
 */

export class ScaleSiteCreatePage {
  readonly page: Page;
  readonly formRoot: Locator;
  readonly siteName: Locator;
  readonly ownerClient: Locator;
  readonly ownerLoc: Locator;
  readonly timberBrand: Locator;
  readonly siteLocation: Locator;
  readonly saveRecordButton: Locator;
  readonly resetButton: Locator;
  readonly formBanner: Locator;

  /** The system-generated id of the last site created via this page (from the post-save view URL). */
  lastCreatedId = '';

  constructor(page: Page) {
    this.page = page;
    // The ScaleSiteForm root — the fill helper is scoped to it (only one such form is on the create route).
    this.formRoot = page.locator('.scale-site-create-form');
    this.siteName = page.locator('#scale-site-name');
    this.ownerClient = page.locator('#client');
    this.ownerLoc = page.locator('#loc');
    this.timberBrand = page.locator('#timber-brand');
    this.siteLocation = page.locator('#site-location-description');
    this.saveRecordButton = page.getByRole('button', { name: 'Save Record' });
    this.resetButton = page.getByRole('button', { name: 'Reset' });
    // The "Save failed." InlineNotification the form shows when the POST is rejected/errors.
    this.formBanner = page.locator('.cds--inline-notification--error');
  }

  /** Log in (mock IDIR) then client-side navigate to the create route so the in-memory session survives. */
  async goto(): Promise<void> {
    await loginAsMockScsUser(this.page);
    await clientSideNavigate(this.page, '/scale-sites/create');
    await this.expectShown();
  }

  /** Readiness: the create form's first field is the stable anchor (PageTitle text is not asserted). */
  async expectShown(): Promise<void> {
    await expect(this.siteName).toBeVisible({ timeout: 30_000 });
    await expect(this.saveRecordButton).toBeVisible();
  }

  /** Apply only the provided fields (shared fill helper, scoped to the form); omitted fields keep defaults. */
  async fill(values: ScaleSiteFormInput): Promise<void> {
    await fillScaleSiteFields(this.formRoot, values);
  }

  /** A full, valid create form (pinned happy-path values), overridable per scenario. */
  async fillValid(overrides: ScaleSiteFormInput = {}): Promise<void> {
    await this.fill({
      siteName: validScaleSite.siteName,
      ownerClient: validOwner.clientNumber,
      ownerLoc: validOwner.loc,
      regDist: regDistOrgUnitNo,
      siteLocation: validScaleSite.siteLocation,
      primaryType: primaryMethodCode,
      secondaryType: secondaryMethodCode,
      ...overrides,
    });
  }

  async clickSave(): Promise<void> {
    await this.saveRecordButton.click();
  }

  /**
   * Fill the valid form and Save. Returns the created id, read from the post-save redirect
   * (/scale-sites/view/{id}); also stored on `lastCreatedId`.
   *
   * BOUNDED RE-SAVE around a KNOWN app concurrency limitation (NOT masking behaviour under test): the
   * scale-site PK is generated by the legacy min-free-id trigger (SCS_SCST_BR_IU_TRG), which RACES under
   * concurrent creates — two overlapping inserts compute the same id, the loser gets ORA-00001 → HTTP 500
   * → the form shows a "Save failed." banner and does not navigate. A failed create rolls back (nothing
   * persisted), so re-Saving recomputes a fresh id. We retry ONLY that transient collision (banner shown,
   * still on the form); on the last attempt the real failure surfaces. See defects.md "concurrency" note.
   * A normal single-pass suite run issues exactly ONE create (S01), so this never fires there — it only
   * hardens the artificial `--repeat-each` self-concurrency in the stress gate.
   *
   * CRITICAL — the retry is gated on the error banner being VISIBLE. A createdId timeout does NOT by itself
   * mean the create failed: the POST may have SUCCEEDED with a merely slow SPA nav (>12s). Re-Saving in that
   * case would create a SECOND site whose id is never captured — a permanent orphan row in the shared seeded
   * DB, invisible to both the createdScaleSiteIds teardown and the residue check. So we only re-Save when the
   * "Save failed." banner is actually up (⇒ rolled back, safe to retry); with no banner we instead wait out
   * the slow navigation and capture the real id, never issuing a second POST.
   */
  async createValid(overrides: ScaleSiteFormInput = {}): Promise<string> {
    await this.fillValid(overrides);
    const maxAttempts = 4;
    for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
      await this.clickSave();
      try {
        return await this.createdId(12_000);
      } catch (err) {
        // Settle the banner state: after a 12s wait the POST has long resolved, so a failure banner (which
        // renders as soon as the POST is rejected) is already present or definitively absent.
        const bannerVisible = await this.formBanner.first().isVisible().catch(() => false);
        if (!bannerVisible) {
          // No "Save failed." banner ⇒ NOT the transient collision. The create likely SUCCEEDED and the SPA
          // nav is just slow — do NOT re-Save (that would orphan a row). Wait out the slow nav and capture the
          // real id; if it still never lands, surface that as a genuine failure (no second POST was issued).
          return await this.createdId(15_000);
        }
        const bannerText = (await this.formBanner.first().textContent().catch(() => null)) ?? '(no banner text)';
        if (attempt === maxAttempts) {
          throw new Error(`Scale site create did not navigate after ${maxAttempts} attempts. Banner: ${bannerText}`);
        }
        // Transient PK-generation collision confirmed (banner up, still on the form). Wait for the button to
        // re-enable (isSubmitting cleared) before re-Saving with the same values. Carry the retry context on
        // the assertion so a button that never re-enables fails with THIS message, not a bare toBeEnabled
        // timeout that would discard the attempt/banner context.
        await expect(
          this.saveRecordButton,
          `Save button did not re-enable after a transient collision (attempt ${attempt}/${maxAttempts}). Banner: ${bannerText}`,
        ).toBeEnabled();
      }
    }
    throw new Error('unreachable');
  }

  /** The created record's id, read from the post-save view URL. Waits web-first for the navigation. */
  async createdId(timeout = 15_000): Promise<string> {
    await expect(this.page).toHaveURL(/\/scale-sites\/view\/[^/]+$/, { timeout });
    const id = decodeURIComponent(this.page.url().split('/scale-sites/view/')[1] ?? '');
    if (!id) throw new Error(`No scale site id in view URL: ${this.page.url()}`);
    this.lastCreatedId = id;
    return id;
  }

  /**
   * Save and capture the POST /api/scale-sites response (for the server-reject S06 path, where the write
   * DOES leave the browser and the backend rejects it). Returns the HTTP status.
   */
  async saveAwaitingCreateResponse(): Promise<number> {
    const [resp] = await Promise.all([
      this.page.waitForResponse(
        (r) => r.request().method() === 'POST' && new URL(r.url()).pathname.endsWith('/scale-sites'),
      ),
      this.clickSave(),
    ]);
    return resp.status();
  }
}
